def write_resx(path, lang_index):
    parts = ['<?xml version="1.0" encoding="utf-8"?>',
             '<root>',
             '  <xsd:schema id="root" xmlns="" xmlns:xsd="http://www.w3.org/2001/XMLSchema" xmlns:msdata="urn:schemas-microsoft-com:xml-msdata">',
             '    <xsd:element name="root" msdata:IsDataSet="true"><xsd:complexType><xsd:choice maxOccurs="unbounded">',
             '      <xsd:element name="data"><xsd:complexType><xsd:sequence><xsd:element name="value" type="xsd:string" minOccurs="0" msdata:Ordinal="1"/></xsd:sequence>',
             '        <xsd:attribute name="name" type="xsd:string" use="required"/></xsd:complexType></xsd:element>',
             '    </xsd:choice></xsd:complexType></xsd:element></xsd:schema>',
             '  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>',
             '  <resheader name="version"><value>2.0</value></resheader>',
             '  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>',
             '  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>']
    for name, en, ru in pairs:
        val = escape(en if lang_index == 0 else ru)
        parts.append(f'  <data name="{name}" xml:space="preserve"><value>{val}</value></data>')
    parts.append('</root>')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(parts))

